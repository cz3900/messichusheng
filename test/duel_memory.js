process.env.AD_COMBO_FAKE='1';
const assert=require('assert/strict'),{SearchMemory}=require('../duel_memory'),{Planner,T}=require('../duel_search');
const B='bristleback_bristleback',Q='bristleback_quill_spray',S='bounty_hunter_wind_walk';
const m=new SearchMemory();m.observe(1,[{key:B,n:16,win:.55},{key:S,n:16,win:.54},{key:'weak',n:16,win:.4}],new Map([[B,new Map([[Q,{n:14,sum:4.7}]])]]));
assert(m.ideas.has(B)&&m.ideas.has(S)&&m.ideas.has('weak'),'Keep all tested alternatives, with stronger discoveries ranked first');
assert.equal(m.ideas.get(B).companions[0].key,Q);
m.observe(7,[{key:B,n:8,win:.6}],new Map());
assert.equal(m.ideas.get(B).step,1,'Future forecast does not erase the earlier discovery usable at L2');
assert.equal(m.ideas.get(B).companions[0].key,Q,'A later incomplete observation retains the known combo');
const sim={items:[{key:B},{key:Q},{key:S}],taken:[false,false,false],step:2,order:[0,5,1,6]},own=new Int8Array([-1,-1,-1]),legal=new Set([B,Q,S]);
assert(m.priorities(sim,own,legal).includes(B));sim.step=3;
assert(m.priorities(sim,own,legal).includes(B),'Right inherits an idea discovered at R1 just as left does');
sim.taken[0]=true;own[0]=6;
assert.equal(m.priorities(sim,own,legal)[0],Q,'Existing anchor reminds its actual owner to complete the kit');
sim.step=2;assert(!m.priorities(sim,own,legal).includes(Q),'Other players do not inherit a kit whose anchor belongs to someone else');
sim.taken[0]=false;own[0]=-1;sim.taken[1]=true;own[1]=5;
assert(!m.priorities(sim,own,legal).includes(B),'Stolen companion removes this combo priority');
own[1]=1;assert(m.priorities(sim,own,legal).includes(B),'Our own companion keeps the reverse-order combo alive');
assert(!m.priorities(sim,own,new Set([S])).includes(B),'Unavailable actions cannot enter inherited candidates');
sim.step=1;assert.equal(m.priorities(sim,own,legal).length,0,'Later evidence never changes an earlier root candidate set');
m.advance([B,Q]);assert(!m.ideas.has(B));
const p=new Planner({compact:true});p.memory.observe(1,[{key:B,n:8,win:.6}],new Map());
const keys=['a','b','c','d','e','f','g','h',B],testSim={items:keys.map(key=>({key})),taken:keys.map(()=>false),step:2,order:[0,5,1]},testOwn=Int8Array.from(keys.map(()=>-1));
const node=p.makeNode(testSim,testOwn,keys.map((key,i)=>({i,p:i===8?1e-15:.125})));assert.equal(node.rows.length,8);
const inherited=p.inheritedRows(node,testSim,testOwn,8);
assert.equal(inherited.rows.length,8);assert.equal(inherited.probes[0].i,8);
assert.equal(inherited.probes[0].n,0);assert.equal(inherited.probes[0].sum,0,'Cross-position ideas never inject wins or visits');
assert.notEqual(p.selectContinuation(node,testSim,testOwn,8).i,8,'A one-off position tries its own network suggestion first');
node.pending=2;assert.equal(p.selectContinuation(node,testSim,testOwn,8).i,8,'Repeated left position explores the remembered action');
node.seat=6;testSim.order[2]=6;assert.equal(p.selectContinuation(node,testSim,testOwn,8).i,8,'Repeated right position explores the same remembered action');
assert.equal(inherited.probes.find(r=>r.n+r.pending<1).i,8);
inherited.probes[0].pending=1;assert(!p.inheritedRows(node,testSim,testOwn,8).probes.find(r=>r.n+r.pending<1),'Parallel trajectories do not repeat the compulsory probe');
const fresh=new Planner();assert.equal(fresh.memory.ideas.size,0,'A new search namespace starts with no ideas');
assert.equal(new Planner({remember:false}).memory,null,'Baseline comparison can disable only inheritance');
assert(!m.ideas.get(S).win,'Memory stores ideas rather than a transferable global win rate');
